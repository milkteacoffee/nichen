/* 全局命名空间（必须最先加载） */
window.G = window.G || {};
/* 游戏内版本号（标题「关于」与关于页显示）。
   ⚠️ **必须与 HANDOVER.md 头部「代码版本」一致** —— 它从 v0.0.2 起就没再同步过，
   一直显示成初始占位（v0.12.0 才发现）。由 smoke 的 `version.contract` 钉住。 */
G.VERSION = 'v2.3.0';

/* ===== 像素风开关（v2.0.0）=====
   用户口径：「转成像素风格，但是现在的素材不要丢弃，可以作为对话或者动画的原图，
            因为像素风格，可能会更偏向俯视角45°」。

   放在**全局命名空间**（最早加载）是有意的：世界层（art / sprites / explore）、
   场景层（game）都要读它，谁都不该通过加载顺序去"先拿到"对方。

   `PIXEL` = 1 显示像素对应几个**逻辑像素**。
   实测（`_gen/_pixel_preview.js` 的对比条）：1.5 能读出干净的像素小人，
   2.5 以上五官就糊了 —— 所以只有 1 / 1.5 / 2 三档，且默认 1.5。
   `PIXEL === 1` 表示**关闭像素化**（逐像素等于历史行为，是零回归的判据值）。

   ⚠️ 分片是**点采样**（不是均值）：像素风的立身之本是"硬边 + 不产生新颜色"，
      均值降采样会把调色板从 20 色糊成数百色，"像素感"当场消失。
   ⚠️ 只作用于**世界层**。界面层（HUD / 对话 / 面板 / 立绘 / 标题）保持平滑 ——
      本作逻辑分辨率只有 480×272，UI 字号 9~12px，像素化会直接糊成不可读的方块
      （用户要求"素材不要丢弃、留作对话原图"正是这个意思）。 */
G.PIXEL = 1.5;
G.pixelOn = function () { return G.PIXEL > 1; };

